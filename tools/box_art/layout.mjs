/** Publish only reviewed printed-content bounds; never inspect image colours or alter image bytes. */
import fs from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
export async function writeLayout(recipePath,destination='src/newer/ui/box_art_layout.js'){
 const recipe=typeof recipePath==='string'?JSON.parse(await fs.readFile(recipePath,'utf8')):recipePath;
 const rows=recipe.faces.filter(f=>f.face==='front'||f.face==='back').map(f=>{
  const {width,height,content}=f;
  if(![width,height,content?.width,content?.height].every(n=>Number.isInteger(n)&&n>0)||!['left','top'].every(k=>Number.isInteger(content[k])&&content[k]>=0)||content.left+content.width>width||content.top+content.height>height)throw Error('Invalid printed-content bounds: '+f.path);
  return '  '+JSON.stringify(f.path)+': '+JSON.stringify({width,height,content});
 });
 await fs.writeFile(destination,'// Generated by tools/box_art/layout.mjs from the retained face derivation.\n// Bounds exclude authoring padding only; spine artwork is never fitted by these bounds.\nexport const BOX_ART_LAYOUT = Object.freeze({\n'+rows.join(',\n')+'\n});\n');
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href)await writeLayout(process.argv[2]??'docs/evidence/box-art-standardization-2026-10-20/derivation.json');
